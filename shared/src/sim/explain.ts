export function explain(e: Pick<SimulationEvent, 'explainKey' | 'explainArgs'>): string {
  const t = T[e.explainKey] ?? e.explainKey;
  return t.replace(/\{(\w+)\}/g, (_, k: string) => String(e.explainArgs[k] ?? `{${k}}`));
}

